export function localizeXmlText(raw: string | undefined, lang: LangCode): string {
  if (!raw) return '';
  if (lang === 'TR') return raw;
  let out = raw;
  for (const [pattern, replacement] of PHRASE_MAP[lang]) {
    out = out.replace(pattern, replacement);
  }
  return out;
}
