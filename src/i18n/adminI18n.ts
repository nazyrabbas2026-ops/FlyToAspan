export function translateAdminText(raw: string, lang: LangCode): string {
  if (!raw || lang === 'TR') return raw;
  const match = raw.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return raw;
  const [, lead, core, trail] = match;
  if (!core) return raw;

  const normalized = core.replace(/\s+/g, ' ');
  const idx = LANG_INDEX[lang];

  // 1. Exact dictionary match
  const exact = EXACT_TRANSLATIONS[normalized];
  if (exact) return `${lead}${exact[idx]}${trail}`;

  // 2. Pattern / dynamic phrase replacements
  let out = normalized;
  for (const [pattern, replacement] of PATTERN_REPLACEMENTS[lang]) {
    out = out.replace(pattern, replacement);
  }
  return out === normalized ? raw : `${lead}${out}${trail}`;
}
